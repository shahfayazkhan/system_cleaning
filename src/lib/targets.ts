import type { CacheTargetDef, CategoryInfo } from "./types";

/**
 * Registry of every cache location the cleaner knows about.
 *
 * RULES FOR ADDING A TARGET
 *  1. The folder must contain ONLY data that its owner app regenerates on its own.
 *  2. Never point at a profile/data folder itself — only at its cache sub-folders
 *     (e.g. Chrome's "Cache", never "Default" which holds history, passwords, cookies).
 *  3. Anything that costs real time/bandwidth to get back is at least "moderate".
 *  4. Anything the user might still want (models, Trash, archives) is "critical".
 *
 * Path tokens: ~ = home, %LOCALAPPDATA%, %APPDATA%, %TEMP%, %WINDIR%, %PROGRAMDATA%, %TMPDIR%.
 * A path segment containing * is expanded (e.g. "Profile *").
 */

