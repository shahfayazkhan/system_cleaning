const chromium = (base: { mac: string; win: string }, sub: string[]) => ({
  darwin: sub.flatMap((s) => [`${base.mac}/Default/${s}`, `${base.mac}/Profile */${s}`]),
  win32: sub.flatMap((s) => [`${base.win}\\Default\\${s}`, `${base.win}\\Profile *\\${s}`]),
});

const electron = (mac: string, win: string, subs = ["Cache", "Code Cache", "GPUCache", "DawnCache", "DawnGraphiteCache", "DawnWebGPUCache"]) => ({
  darwin: subs.map((s) => `~/Library/Application Support/${mac}/${s}`),
  win32: subs.map((s) => `%APPDATA%\\${win}\\${s}`),
  linux: subs.map((s) => `~/.config/${mac}/${s}`),
});

